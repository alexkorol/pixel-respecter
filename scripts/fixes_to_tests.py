"""Generate pytest regressions from Fix Lab decisions and ground truths."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "benchmarks" / "wild_corpus"
DEFAULT_OUTPUT = ROOT / "tests" / "test_ground_truth.py"


def load_decisions(path: Path) -> list[dict]:
    """Read valid decision objects from a JSONL file."""
    decisions = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            decisions.append(json.loads(line))
    return decisions


def build_cases(ids: set[str] | None = None) -> list[dict]:
    cases = []
    fixes_dir = CORPUS / "fixes"
    if not fixes_dir.exists():
        return cases
    for path in sorted(fixes_dir.glob("*.jsonl")):
        image_id = path.stem
        if ids and image_id not in ids:
            continue
        # A JSONL file appears as soon as calibration begins, while the PNG is
        # written only when the sprite is marked complete.  Regressions should
        # represent completed calibrations, not in-progress editor sessions.
        if not (CORPUS / "ground_truth" / f"{image_id}.png").exists():
            continue
        decisions = load_decisions(path)
        pitch = next(
            (item for item in reversed(decisions) if item.get("kind") == "pitch_pick"),
            None,
        )
        cells: dict[tuple[int, int], list[int]] = {}
        transparency = None
        crop = None
        for item in decisions:
            if item.get("kind") == "pitch_pick":
                # Choosing a new base candidate resets the editor canvas.
                cells.clear()
                transparency = None
                crop = None
            elif item.get("kind") == "cell_vote":
                x, y = item["context"]["cell"]
                cells[(x, y)] = item["choice"]["color"]
            elif item.get("kind") == "freehand":
                x, y = item["context"]["cell"]
                cells[(x, y)] = item["choice"]["color"]
            elif item.get("kind") == "palette_merge":
                old = item["choice"]["merged"]
                new = item["choice"]["target"]
                cells = {
                    coord: (new if color == old else color)
                    for coord, color in cells.items()
                }
            elif item.get("kind") == "transparency":
                transparency = item["choice"]
            elif item.get("kind") == "crop":
                crop = {
                    "context": item["context"],
                    "choice": item["choice"],
                }
        cases.append({
            "id": image_id,
            "pitch": pitch["choice"] if pitch else None,
            "cells": [[x, y, color] for (x, y), color in sorted(cells.items())],
            "transparency": transparency,
            "crop": crop,
        })
    return cases


def render_test_file(cases: list[dict]) -> str:
    payload = json.dumps(cases, indent=2)
    return f'''"""Generated by scripts/fixes_to_tests.py; do not edit by hand."""

import json
from pathlib import Path

import numpy as np
import pytest
from PIL import Image

from pixel_perfecter.reconstructor import PixelArtReconstructor

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "benchmarks" / "wild_corpus"
CASES = json.loads(r\'\'\'{payload}\'\'\')
MANIFEST = {{entry["id"]: entry for entry in json.loads(
    (CORPUS / "manifest.json").read_text(encoding="utf-8")
)["entries"]}}


@pytest.mark.parametrize("case", CASES, ids=lambda case: case["id"])
def test_fixlab_ground_truth(case):
    truth_path = CORPUS / "ground_truth" / f"{{case['id']}}.png"
    assert truth_path.exists(), f"missing Fix Lab ground truth: {{truth_path}}"
    with Image.open(truth_path) as image:
        truth = np.asarray(image.convert("RGBA"))
    assert truth.ndim == 3 and truth.shape[2] == 4
    assert truth.shape[0] > 0 and truth.shape[1] > 0
    crop = case["crop"]
    if crop and crop["choice"]["enabled"]:
        x0, y0, x1, y1 = crop["choice"]["bounds"]
        assert [truth.shape[1], truth.shape[0]] == crop["choice"]["output_size"]
    else:
        x0, y0 = 0, 0
        x1, y1 = truth.shape[1], truth.shape[0]
    for x, y, color in case["cells"]:
        if x0 <= x < x1 and y0 <= y < y1:
            assert truth[y - y0, x - x0, :3].tolist() == color
    if case["transparency"]:
        if not case["transparency"]["enabled"]:
            assert np.all(truth[:, :, 3] == 255)


@pytest.mark.parametrize(
    "case", [
        case for case in CASES
        if case["pitch"] and case["id"] in MANIFEST
    ],
    ids=lambda case: case["id"],
)
def test_fixlab_pitch_remains_a_machine_candidate(case):
    entry = MANIFEST[case["id"]]
    with Image.open(CORPUS / entry["file"]) as image:
        source = np.asarray(image.convert("RGB"))
    rec = PixelArtReconstructor(image=source)
    rec.run("global")
    choice = case["pitch"]
    if choice["kind"] == "mesh":
        pitches = [item["pitch"] for item in rec.last_fit_debug["mesh_candidates"]]
        assert any(abs(pitch - choice["pitch"]) <= 0.25 for pitch in pitches)
    else:
        sizes = [item["size"] for item in rec.last_fit_debug["candidates"]]
        assert choice["size"] in sizes
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", help="Comma-separated image ids")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    ids = set(args.only.split(",")) if args.only else None
    cases = build_cases(ids)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_test_file(cases), encoding="utf-8", newline="\n")
    print(f"Wrote {len(cases)} Fix Lab cases to {args.output}")


if __name__ == "__main__":
    main()
